#!/usr/bin/env python3
"""build.py: bootstraps the quine relay ONCE, then never touches a hop again.

🔁 What it does (RELAY_PLAN.md v1, frozen):
  1. reads the three templates as raw bytes: templates/T_apl, T_sno, T_fs
  2. B = T_apl + SEP + T_sno + SEP + T_fs + SEP      (SEP = b"=====HOP=====\\n")
  3. writes relay.apl = T_apl with its one "@@\\n" line replaced by B as APL data lines

That is the ONLY job Python has. After relay.apl exists, every hop is regenerated by
APL / SNOBOL4 / Forth from what's embedded in its own source (Nova's fence).

Also has a --render mode so each pair can see exactly what THEIR hop must print:
  python3 build.py --render sno   -> what hop1.sno should be (T_sno + B in SNOBOL4 format)
  python3 build.py --render fs    -> what hop2.fs should be
  python3 build.py --render apl   -> what hop3.apl should be (== relay.apl)
Those are the per-hop known answers. A hop passes when `cmp` against them is silent.

📏 Bytes: everything here is bytes. No text mode, no newline translation, no BOM.
"""
import sys, pathlib

HERE = pathlib.Path(__file__).resolve().parent
TPL = HERE / "templates"
SEP = b"=====HOP=====\n"
PLACEHOLDER = b"@@\n"
PER_LINE = 20

# 🧬 one data line per language, frozen in RELAY_PLAN.md
def line_apl(nums):  return b"B\xe2\x86\x90B," + b" ".join(nums) + b"\n"          # B←B,n n n
def line_sno(nums):  return b"        D = D '" + b" ".join(nums) + b" '\n"      # 8 spaces, trailing space inside quote
def line_fs(nums):   return b" ".join(nums) + b" D,\n"                          # n n n D,
FORMAT = {"apl": line_apl, "sno": line_sno, "fs": line_fs}


def load(name):
    data = (TPL / name).read_bytes()
    assert data.count(PLACEHOLDER) == 1 and (data.startswith(PLACEHOLDER) or b"\n" + PLACEHOLDER in data), \
        f"{name}: needs exactly one line that is just @@"
    assert data.endswith(b"\n") and not data.endswith(b"\n\n"), f"{name}: must end with exactly one \\n"
    assert b"\r" not in data, f"{name}: CR found, LF only"
    assert SEP not in data, f"{name}: contains the separator line"
    return data


def payload():
    t = {k: load(f"T_{k}") for k in ("apl", "sno", "fs")}
    for k in ("sno", "fs"):
        assert all(b < 128 for b in t[k]), f"T_{k} must be pure ASCII"
    return t, t["apl"] + SEP + t["sno"] + SEP + t["fs"] + SEP


def render(lang, t, B):
    nums = [str(b).encode() for b in B]
    lines = b"".join(FORMAT[lang](nums[i:i + PER_LINE]) for i in range(0, len(nums), PER_LINE))
    return t[lang].replace(PLACEHOLDER, lines, 1)


if __name__ == "__main__":
    t, B = payload()
    if len(sys.argv) == 3 and sys.argv[1] == "--render":
        sys.stdout.buffer.write(render(sys.argv[2], t, B))
    else:
        out = HERE / "relay.apl"
        out.write_bytes(render("apl", t, B))
        print(f"wrote {out} ({out.stat().st_size} bytes; B = {len(B)} bytes, "
              f"{(len(B) + PER_LINE - 1) // PER_LINE} data lines per hop)")
